#[derive(Debug, Clone, Default)]
pub struct HuntElementProfile {
    pub weaknesses: &'static [&'static str],
    pub resistances: &'static [&'static str],
}

impl HuntElementProfile {
    pub fn has_weakness(&self, element: &str) -> bool {
        self.weaknesses.iter().any(|&w| w == element)
    }

    pub fn has_resistance(&self, element: &str) -> bool {
        self.resistances.iter().any(|&r| r == element)
    }
}

